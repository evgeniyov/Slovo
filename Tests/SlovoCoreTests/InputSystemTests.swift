import AppKit
import ApplicationServices
import Foundation
import XCTest
@testable import SlovoCore

/// Text insertion against a private pasteboard with a fake keystroke, plus the small
/// pure parts of permissions, shortcuts, the frontmost app and Fn warnings. Nothing
/// here posts real key events or registers global shortcuts.
@MainActor
final class InputSystemTests: XCTestCase {
    private var pasteboard = NSPasteboard(name: NSPasteboard.Name("local.slovo.tests.placeholder"))
    private let permissions = FakePermissions()
    private var keystrokes = 0
    private var keystrokeSucceeds = true
    private var focusedTarget = TextInsertionTarget(processID: 1)
    private let customType = NSPasteboard.PasteboardType("local.slovo.tests.custom")

    override func setUp() async throws {
        pasteboard = NSPasteboard(name: NSPasteboard.Name("local.slovo.tests.\(UUID().uuidString)"))
        permissions.accessibility = .granted
        permissions.secureInput = false
        keystrokes = 0
        keystrokeSucceeds = true
        focusedTarget = TextInsertionTarget(processID: 1)
    }

    override func tearDown() async throws {
        pasteboard.releaseGlobally()
    }

    // MARK: - TextInserter

    func testEmptyTextInsertsNothing() async {
        let inserter = makeInserter()
        let result = await inserter.insert(" \n ")
        XCTAssertEqual(result, .empty)
        XCTAssertEqual(keystrokes, 0)
    }

    func testSecureInputCopiesWithMarkers() async throws {
        permissions.secureInput = true
        let inserter = makeInserter()
        let result = await inserter.insert("пароль не вставляем")
        XCTAssertEqual(result, .copied(.secureInput))
        XCTAssertEqual(keystrokes, 0)
        XCTAssertEqual(pasteboard.string(forType: .string), "пароль не вставляем")
        let types = try XCTUnwrap(pasteboard.types)
        XCTAssertTrue(types.contains(TextInserter.transientType))
        XCTAssertTrue(types.contains(TextInserter.autoGeneratedType))
    }

    func testSecureInputInAnotherAppUsesTheOriginalEditorsSelection() async {
        permissions.secureInput = true
        focusedTarget.element = AXUIElementCreateApplication(10)
        writeOriginal("user clipboard")
        var replacedText: String?
        let inserter = makeInserter { text, element in
            XCTAssertEqual(element, self.focusedTarget.element)
            replacedText = text
            return true
        }

        let result = await inserter.insert("dictated text", into: inserter.captureTarget())

        XCTAssertEqual(result, .pasted)
        XCTAssertEqual(replacedText, "dictated text")
        XCTAssertEqual(keystrokes, 0)
        XCTAssertEqual(pasteboard.string(forType: .string), "user clipboard")
    }

    func testSecureInputDoesNotInsertIfFocusChanged() async {
        permissions.secureInput = true
        focusedTarget.element = AXUIElementCreateApplication(10)
        let inserter = makeInserter { _, _ in
            XCTFail("The editor that now has focus must not receive this dictation")
            return true
        }
        let original = inserter.captureTarget()
        focusedTarget.element = AXUIElementCreateApplication(11)

        let result = await inserter.insert("dictated text", into: original)

        XCTAssertEqual(result, .copied(.focusChanged))
        XCTAssertEqual(keystrokes, 0)
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated text")
    }

    func testAccessibleInsertionRequiresAnIdentifiableOrdinaryEditor() {
        XCTAssertTrue(TextInserter.isOrdinaryEditor(role: kAXTextAreaRole, subrole: nil))
        XCTAssertFalse(TextInserter.isOrdinaryEditor(role: kAXTextFieldRole, subrole: kAXSecureTextFieldSubrole))
        XCTAssertFalse(TextInserter.isOrdinaryEditor(role: "AXWebArea", subrole: nil))
        XCTAssertFalse(TextInserter.isOrdinaryEditor(role: nil, subrole: nil))
    }

    func testMissingAccessibilityCopies() async {
        permissions.accessibility = .denied
        let inserter = makeInserter()
        let result = await inserter.insert("hello")
        XCTAssertEqual(result, .copied(.accessibilityMissing))
        XCTAssertEqual(keystrokes, 0)
        XCTAssertEqual(pasteboard.string(forType: .string), "hello")
    }

    func testPasteUsesTheSameFocusedElement() async {
        focusedTarget.element = AXUIElementCreateApplication(10)
        let inserter = makeInserter()
        let target = inserter.captureTarget()
        focusedTarget.element = AXUIElementCreateApplication(10)

        let result = await inserter.insert("dictated text", into: target)

        XCTAssertEqual(result, .pasted)
        XCTAssertEqual(keystrokes, 1)
    }

    func testChangedFocusedElementCopiesWithoutPostingAKeystroke() async {
        focusedTarget.element = AXUIElementCreateApplication(10)
        let inserter = makeInserter()
        let target = inserter.captureTarget()
        focusedTarget.element = AXUIElementCreateApplication(11)

        let result = await inserter.insert("dictated text", into: target)

        XCTAssertEqual(result, .copied(.focusChanged))
        XCTAssertEqual(keystrokes, 0)
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated text")
    }

    func testChangedAppWithNoAccessibilityElementCopies() async {
        let inserter = makeInserter()
        let target = inserter.captureTarget()
        focusedTarget = TextInsertionTarget(processID: 2)

        let result = await inserter.insert("dictated text", into: target)

        XCTAssertEqual(result, .copied(.focusChanged))
        XCTAssertEqual(keystrokes, 0)
    }

    func testChangedWindowWithNoAccessibilityElementCopies() async {
        focusedTarget.window = AXUIElementCreateApplication(10)
        let inserter = makeInserter()
        let target = inserter.captureTarget()
        focusedTarget.window = AXUIElementCreateApplication(11)

        let result = await inserter.insert("dictated text", into: target)

        XCTAssertEqual(result, .copied(.focusChanged))
        XCTAssertEqual(keystrokes, 0)
    }

    func testPasteRestoresThePreviousItems() async throws {
        writeOriginal("user clipboard")
        let inserter = makeInserter()
        let result = await inserter.insert("dictated text")
        XCTAssertEqual(result, .pasted)
        XCTAssertEqual(keystrokes, 1)
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated text")
        XCTAssertTrue(pasteboard.types?.contains(TextInserter.transientType) ?? false)

        try await Task.sleep(for: .milliseconds(300))
        XCTAssertEqual(pasteboard.string(forType: .string), "user clipboard")
        XCTAssertEqual(pasteboard.data(forType: customType), Data([7, 8, 9]))
        XCTAssertFalse(pasteboard.types?.contains(TextInserter.transientType) ?? true)
    }

    func testRestoreSkipsWhenSomeoneCopiedMeanwhile() async throws {
        writeOriginal("user clipboard")
        let inserter = makeInserter()
        _ = await inserter.insert("dictated text")
        pasteboard.clearContents()
        pasteboard.setString("copied during the delay", forType: .string)
        try await Task.sleep(for: .milliseconds(300))
        XCTAssertEqual(pasteboard.string(forType: .string), "copied during the delay")
    }

    func testBackToBackPastesRestoreTheOriginalClipboard() async throws {
        writeOriginal("user clipboard")
        let inserter = makeInserter()
        _ = await inserter.insert("first")
        _ = await inserter.insert("second")
        XCTAssertEqual(pasteboard.string(forType: .string), "second")
        XCTAssertEqual(keystrokes, 2)
        try await Task.sleep(for: .milliseconds(300))
        XCTAssertEqual(pasteboard.string(forType: .string), "user clipboard")
    }

    func testEmptyClipboardIsRestoredEmpty() async throws {
        pasteboard.clearContents()
        let inserter = makeInserter()
        _ = await inserter.insert("text")
        try await Task.sleep(for: .milliseconds(300))
        XCTAssertNil(pasteboard.string(forType: .string))
    }

    func testFailedKeystrokeLeavesTheTextToPasteByHand() async throws {
        writeOriginal("user clipboard")
        keystrokeSucceeds = false
        let inserter = makeInserter()
        let result = await inserter.insert("dictated text")
        XCTAssertEqual(result, .copied(.pasteFailed))
        try await Task.sleep(for: .milliseconds(300))
        XCTAssertEqual(pasteboard.string(forType: .string), "dictated text")
    }

    func testCopyCancelsAPendingRestore() async throws {
        writeOriginal("user clipboard")
        let inserter = makeInserter()
        _ = await inserter.insert("dictated text")
        inserter.copyToPasteboard("paste last transcript")
        try await Task.sleep(for: .milliseconds(300))
        XCTAssertEqual(pasteboard.string(forType: .string), "paste last transcript")
    }

    // MARK: - Small pure parts

    func testSettingsLinksPointAtPrivacyPanes() throws {
        let anchors: [PermissionKind: String] = [
            .microphone: "Privacy_Microphone", .accessibility: "Privacy_Accessibility",
            .inputMonitoring: "Privacy_ListenEvent", .systemAudioRecording: "Privacy_AudioCapture",
            .screenRecording: "Privacy_ScreenCapture"
        ]
        for kind in PermissionKind.allCases {
            let url = try XCTUnwrap(Permissions.settingsURL(for: kind))
            XCTAssertEqual(url.scheme, "x-apple.systempreferences")
            XCTAssertTrue(url.absoluteString.hasSuffix("?\(try XCTUnwrap(anchors[kind]))"), url.absoluteString)
        }
    }

    func testPermissionsReportSystemAudioAsUnknown() {
        let permissions = Permissions()
        XCTAssertEqual(permissions.status(of: .systemAudioRecording), .unknown)
        XCTAssertEqual(Set(permissions.statuses.keys), Set(PermissionKind.allCases))
    }

    func testCarbonModifiers() {
        XCTAssertEqual(PasteLastShortcut.carbonModifiers([.control, .command]), 0x1100)
        XCTAssertEqual(PasteLastShortcut.carbonModifiers([.option, .shift]), 0x0A00)
        XCTAssertEqual(PasteLastShortcut.carbonModifiers([]), 0)
        XCTAssertNil(PasteLastShortcut().shortcut)
    }

    func testFrontmostAppIgnoresSlovoItself() {
        XCTAssertNil(FrontmostApp.identity(bundleID: "local.slovo.Slovo", name: "Slovo", ownBundleID: "local.slovo.Slovo"))
        XCTAssertNil(FrontmostApp.identity(bundleID: nil, name: "Nameless", ownBundleID: "local.slovo.Slovo"))
        XCTAssertEqual(FrontmostApp.identity(bundleID: "ru.keepcoder.Telegram", name: "Telegram", ownBundleID: "local.slovo.Slovo"),
                       AppIdentity(bundleID: "ru.keepcoder.Telegram", name: "Telegram"))
        XCTAssertEqual(FrontmostApp.identity(bundleID: "com.example.app", name: " ", ownBundleID: nil)?.name, "com.example.app")
    }

    func testFnWarnings() {
        XCTAssertEqual(FnKeyConflicts.warnings(for: .rightOption, fnUsage: 1, wisprFlowRunning: true), [])
        XCTAssertEqual(FnKeyConflicts.warnings(for: .fn, fnUsage: 0, wisprFlowRunning: false), [])
        XCTAssertEqual(FnKeyConflicts.warnings(for: .fn, fnUsage: 1, wisprFlowRunning: false), [.systemUsesFn(usage: 1)])
        XCTAssertEqual(FnKeyConflicts.warnings(for: .fn, fnUsage: nil, wisprFlowRunning: true),
                       [.systemUsesFn(usage: nil), .wisprFlowRunning])
        XCTAssertNotNil(FnKeyConflicts.keyboardSettingsURL)
        for key in ["input.fn.warning.systemUsage", "input.fn.warning.wisprFlow", "input.fn.openKeyboardSettings"] {
            XCTAssertNotEqual(CoreStrings.string(key, table: .input, language: .en), key)
            XCTAssertNotEqual(CoreStrings.string(key, table: .input, language: .ru),
                              CoreStrings.string(key, table: .input, language: .en))
        }
    }

    func testMonitorSyncWithoutTapIsHarmless() {
        let uptime = FakeUptime()
        let monitor = HotkeyMonitor(uptime: uptime)
        monitor.syncRecording(mode: .handsFree)
        monitor.update(configuration: HotkeyConfiguration(key: .fn))
        monitor.syncRecording(mode: nil)
        monitor.stop()
        XCTAssertFalse(monitor.isRunning)
        XCTAssertFalse(monitor.isKeyDown)
    }

    // MARK: - Helpers

    private func makeInserter(replaceSelection: @escaping TextInserter.ReplaceSelection = { _, _ in false }) -> TextInserter {
        TextInserter(permissions: permissions, pasteboard: pasteboard, restoreDelay: .milliseconds(60),
                     readTarget: { self.focusedTarget }, replaceSelection: replaceSelection) { [weak self] in
            guard let self else { return false }
            self.keystrokes += 1
            return self.keystrokeSucceeds
        }
    }

    private func writeOriginal(_ text: String) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data([7, 8, 9]), forType: customType)
        pasteboard.writeObjects([item])
    }
}

@MainActor
private final class FakePermissions: PermissionsProviding {
    var accessibility: PermissionStatus = .granted
    var secureInput = false

    func status(of kind: PermissionKind) -> PermissionStatus {
        kind == .accessibility ? accessibility : .granted
    }

    func request(_ kind: PermissionKind) async -> PermissionStatus {
        status(of: kind)
    }

    func openSystemSettings(for kind: PermissionKind) {}

    var isSecureInputActive: Bool {
        secureInput
    }
}

private struct FakeUptime: UptimeProviding {
    func uptime() -> TimeInterval {
        100
    }
}
