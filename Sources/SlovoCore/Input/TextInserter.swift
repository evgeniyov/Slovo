import AppKit
import ApplicationServices
import Carbon.HIToolbox
import CoreGraphics
import Foundation

/// The frontmost process and its focused window and element at the start of dictation.
/// Some editors omit AX attributes, so compare the identities macOS actually exposed.
public struct TextInsertionTarget: Equatable {
    let processID: pid_t?
    var window: AXUIElement? = nil
    var element: AXUIElement? = nil

    func matches(_ current: TextInsertionTarget) -> Bool {
        guard let processID, processID == current.processID else { return false }
        if let window, window != current.window { return false }
        if let element, element != current.element { return false }
        return true
    }
}

/// Pastes text into the focused field.
///
/// Saves the pasteboard, writes the text with the `org.nspasteboard.TransientType`
/// and `org.nspasteboard.AutoGeneratedType` markers, posts Command+V as the physical
/// V key to `.cghidEventTap`, then restores the previous items after 1 s if the
/// `changeCount` is still Slovo's. Under Secure Event Input, uses Accessibility to
/// replace the selection of a confirmed ordinary editor. Protected or unsupported
/// fields still get the clipboard fallback.
@MainActor
public final class TextInserter: TextInserting {
    /// Clipboard managers skip items carrying these markers (nspasteboard.org).
    public static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    public static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    /// How long the target app gets to read the pasteboard before it is restored.
    public static let restoreDelay: Duration = .seconds(1)
    /// Some apps (Electron, remote desktops) miss a Command+V shorter than this.
    public static let chordHold: Duration = .milliseconds(60)

    /// Posts the paste keystroke; false when the events could not be created.
    typealias PasteKeystroke = @MainActor () async -> Bool
    typealias ReplaceSelection = @MainActor (String, AXUIElement) -> Bool

    private let permissions: PermissionsProviding
    private let pasteboard: NSPasteboard
    private let readTarget: @MainActor () -> TextInsertionTarget
    private let replaceSelection: ReplaceSelection
    private let pasteKeystroke: PasteKeystroke
    private let delay: Duration
    private var pendingRestore: PendingRestore?
    private var restoreTask: Task<Void, Never>?
    /// The insert in progress. The next one waits for it, so a second paste never
    /// replaces the pasteboard while the target app may still be reading the first.
    private var currentInsert: Task<InsertionResult, Never>?
    private let logger = SlovoLog.logger("TextInserter")

    public convenience init(permissions: PermissionsProviding) {
        self.init(permissions: permissions, pasteboard: .general, restoreDelay: Self.restoreDelay,
                  pasteKeystroke: { await TextInserter.postCommandV(hold: TextInserter.chordHold) })
    }

    /// Tests pass a private pasteboard and a fake keystroke so nothing is pasted for real.
    init(permissions: PermissionsProviding, pasteboard: NSPasteboard, restoreDelay: Duration,
         readTarget: @escaping @MainActor () -> TextInsertionTarget = TextInserter.focusedTarget,
         replaceSelection: @escaping ReplaceSelection = TextInserter.replaceSelectedText,
         pasteKeystroke: @escaping PasteKeystroke) {
        self.permissions = permissions
        self.pasteboard = pasteboard
        self.delay = restoreDelay
        self.readTarget = readTarget
        self.replaceSelection = replaceSelection
        self.pasteKeystroke = pasteKeystroke
    }

    public func captureTarget() -> TextInsertionTarget {
        readTarget()
    }

    public func insert(_ text: String, into target: TextInsertionTarget?) async -> InsertionResult {
        let previous = currentInsert
        let insertion = Task { [weak self] () -> InsertionResult in
            _ = await previous?.value
            guard let self else { return .empty }
            return await self.performInsert(text, into: target)
        }
        currentInsert = insertion
        return await insertion.value
    }

    public func copyToPasteboard(_ text: String) {
        cancelRestore()
        write(text)
    }

    private func performInsert(_ text: String, into target: TextInsertionTarget?) async -> InsertionResult {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return .empty }
        let secureInput = permissions.isSecureInputActive
        guard permissions.status(of: .accessibility) == .granted else {
            copyToPasteboard(text)
            return .copied(secureInput ? .secureInput : .accessibilityMissing)
        }

        if target != nil || secureInput {
            let current = readTarget()
            if let target, !target.matches(current) {
                copyToPasteboard(text)
                return .copied(.focusChanged)
            }
            // Secure Event Input can remain active in a background app. Replacing a
            // regular editor's selection uses its Accessibility API without sending keys.
            if secureInput || permissions.isSecureInputActive {
                if let element = current.element, replaceSelection(text, element) {
                    logger.info("Inserted using Accessibility during Secure Event Input")
                    return .pasted
                }
                copyToPasteboard(text)
                return .copied(.secureInput)
            }
        }

        let previous = snapshotForRestore()
        let written = write(text)
        // Recorded before the keystroke: an insert that starts while this chord is held
        // finds the user's items here instead of snapshotting Slovo's own text.
        restoreTask?.cancel()
        restoreTask = nil
        pendingRestore = PendingRestore(items: previous, changeCount: written)
        let posted = await pasteKeystroke()
        // A newer insert took over the pasteboard and restores the same items itself.
        guard pendingRestore?.changeCount == written else {
            return posted ? .pasted : .copied(.pasteFailed)
        }
        guard posted else {
            logger.error("Could not create the Command+V events")
            cancelRestore()
            return .copied(.pasteFailed)
        }
        scheduleRestore(PendingRestore(items: previous, changeCount: written))
        return .pasted
    }

    private static func focusedTarget() -> TextInsertionTarget {
        guard let pid = NSWorkspace.shared.frontmostApplication?.processIdentifier else {
            return TextInsertionTarget(processID: nil)
        }
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, FocusedInputWatcher.messagingTimeout)
        let element = FocusedInputWatcher.element(app, kAXFocusedUIElementAttribute) ?? systemFocusedElement(for: pid)
        let window = FocusedInputWatcher.element(app, kAXFocusedWindowAttribute)
        guard NSWorkspace.shared.frontmostApplication?.processIdentifier == pid else {
            return TextInsertionTarget(processID: nil)
        }
        return TextInsertionTarget(processID: pid, window: window, element: element)
    }

    private static func systemFocusedElement(for pid: pid_t) -> AXUIElement? {
        let system = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(system, FocusedInputWatcher.messagingTimeout)
        guard let element = FocusedInputWatcher.element(system, kAXFocusedUIElementAttribute) else { return nil }
        var owner: pid_t = 0
        return AXUIElementGetPid(element, &owner) == .success && owner == pid ? element : nil
    }

    private static func replaceSelectedText(_ text: String, in element: AXUIElement) -> Bool {
        AXUIElementSetMessagingTimeout(element, FocusedInputWatcher.messagingTimeout)
        let role = FocusedInputWatcher.string(element, kAXRoleAttribute)
        let subrole = FocusedInputWatcher.string(element, kAXSubroleAttribute)
        guard isOrdinaryEditor(role: role, subrole: subrole) else { return false }
        var settable: DarwinBoolean = false
        guard AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success,
              settable.boolValue else { return false }
        // The element is addressed directly, and this check avoids changing it if its app
        // lost focus while it was answering the accessibility requests above.
        guard element == focusedTarget().element else { return false }
        return AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success
    }

    static func isOrdinaryEditor(role: String?, subrole: String?) -> Bool {
        guard let role, subrole != kAXSecureTextFieldSubrole else { return false }
        return FocusedInputWatcher.textRoles.contains(role)
    }

    // MARK: - Pasteboard

    private struct SavedItem {
        var representations: [(type: NSPasteboard.PasteboardType, data: Data)]
    }

    private struct PendingRestore {
        var items: [SavedItem]
        var changeCount: Int
    }

    /// The user's items to put back later. While an earlier paste still waits for its
    /// restore, the pasteboard holds Slovo's text, so the earlier snapshot is reused.
    private func snapshotForRestore() -> [SavedItem] {
        if let pendingRestore, pendingRestore.changeCount == pasteboard.changeCount {
            return pendingRestore.items
        }
        return (pasteboard.pasteboardItems ?? []).map { item in
            SavedItem(representations: item.types.compactMap { type in
                item.data(forType: type).map { (type: type, data: $0) }
            })
        }
    }

    /// Clears the pasteboard for Slovo's own writes. `currentHostOnly` keeps them off
    /// Universal Clipboard: dictated text is meant for one paste on this Mac, and the
    /// user's restored items were shared already when they were copied.
    private func prepareForWriting() {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
    }

    @discardableResult
    private func write(_ text: String) -> Int {
        prepareForWriting()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    private func scheduleRestore(_ restore: PendingRestore) {
        restoreTask?.cancel()
        pendingRestore = restore
        let delay = self.delay
        restoreTask = Task { [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled else { return }
            self?.restoreIfUnchanged(restore)
        }
    }

    private func cancelRestore() {
        restoreTask?.cancel()
        restoreTask = nil
        pendingRestore = nil
    }

    /// Puts the previous items back unless someone copied something since Slovo wrote.
    private func restoreIfUnchanged(_ restore: PendingRestore) {
        guard pendingRestore?.changeCount == restore.changeCount else { return }
        pendingRestore = nil
        restoreTask = nil
        guard pasteboard.changeCount == restore.changeCount else { return }
        prepareForWriting()
        let items = restore.items.map { saved -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for representation in saved.representations {
                item.setData(representation.data, forType: representation.type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }

    // MARK: - Keystroke

    /// Command down, V down, a short hold, V up, Command up, posted at the HID level so
    /// the target app sees an ordinary physical paste. Keycode 9 is the V position on
    /// every layout, which is what macOS matches shortcuts against.
    static func postCommandV(hold: Duration) async -> Bool {
        let source = CGEventSource(stateID: .combinedSessionState)
        let commandKey = CGKeyCode(kVK_Command)
        let vKey = CGKeyCode(kVK_ANSI_V)
        guard let commandDown = CGEvent(keyboardEventSource: source, virtualKey: commandKey, keyDown: true),
              let vDown = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: true),
              let vUp = CGEvent(keyboardEventSource: source, virtualKey: vKey, keyDown: false),
              let commandUp = CGEvent(keyboardEventSource: source, virtualKey: commandKey, keyDown: false) else {
            return false
        }
        // Explicit flags keep a still-held dictation modifier (Control, Option) out of
        // the chord, which would otherwise turn it into "Paste and Match Style".
        commandDown.flags = .maskCommand
        vDown.flags = .maskCommand
        vUp.flags = .maskCommand
        commandUp.flags = []
        commandDown.post(tap: .cghidEventTap)
        vDown.post(tap: .cghidEventTap)
        try? await Task.sleep(for: hold)
        vUp.post(tap: .cghidEventTap)
        commandUp.post(tap: .cghidEventTap)
        return true
    }
}
