def rate(speaker):
    return VOICES[speaker].get("rate", 1.0)


def text_seconds(text, speaker):
    return len(text) / CHARS_PER_SECOND / rate(speaker) + 0.1


def build(name, seed, speakers, system, count, topic, long_range, medium_range):
    rng = random.Random(seed)
    classes = ["short"] * round(count * 0.2) + ["long"] * round(count * 0.3)
    classes += ["medium"] * (count - len(classes))
    rng.shuffle(classes)
    if classes[0] == "short":
        swap = classes.index("medium")
        classes[0], classes[swap] = classes[swap], classes[0]

    sentences = TOPICS[topic] + COMMON
    unused = sentences[:]
    rng.shuffle(unused)

    def next_sentence(min_chars, max_chars):
        nonlocal unused
        for index, sentence in enumerate(unused):
            if min_chars <= len(sentence) <= max_chars:
                return unused.pop(index)
        pool = [s for s in sentences if min_chars <= len(s) <= max_chars] or sentences
        return rng.choice(pool)

    # Exactly one turn in ten starts before the previous one ends.
    negatives = set(rng.sample(range(1, count), round((count - 1) * 0.1)))

    turns = []
    previous = None
    estimate = 0.0
    for index, kind in enumerate(classes):
        candidates = [s for s in speakers if s != previous]
        # Give the local speaker a little more airtime in calls.
        weights = [1.4 if (s == "A" and system) else 1.0 for s in candidates]
        speaker = rng.choices(candidates, weights=weights)[0]
        gap = 0.0 if index == 0 else (round(rng.uniform(-0.3, -0.05), 2) if index in negatives
                                      else round(rng.uniform(0.1, 1.5), 2))
        turn = {"speaker": speaker}
        if kind == "short":
            turn["text"] = rng.choice(BACKCHANNELS)
            seconds = 0.7
        elif kind == "medium":
            low, high = medium_range
            chars = CHARS_PER_SECOND * rate(speaker)
            turn["text"] = next_sentence(int(low * chars), int(high * chars))
            seconds = text_seconds(turn["text"], speaker)
        else:
            target = rng.uniform(*long_range)
            parts = []
            while text_seconds(" ".join(parts), speaker) < target:
                parts.append(next_sentence(30, 110))
            if text_seconds(" ".join(parts), speaker) > 28:
                parts.pop()
            turn["text"] = " ".join(parts)
            seconds = text_seconds(turn["text"], speaker)
        turn["gap"] = gap
        turns.append(turn)
        previous = speaker
        estimate += seconds + max(gap, -0.3)

    voices = {}
    for speaker in speakers:
        voice = dict(VOICES[speaker])
        if speaker in system:
            voice["track"] = "system"
        voices[speaker] = voice
    scenario = {"name": name, "seed": seed, "me": "A", "voices": voices, "turns": turns}
    kinds = {k: classes.count(k) for k in ("short", "medium", "long")}
    return scenario, estimate, kinds


def main(output):
    output.mkdir(parents=True, exist_ok=True)
    for spec in SCENARIOS:
        scenario, estimate, kinds = build(*spec)
        path = output / f"{scenario['name']}.json"
        text = json.dumps(scenario, ensure_ascii=False, indent=2) + "\n"
        path.write_text(text, encoding="utf-8")
        print(f"{scenario['name']}: {len(scenario['turns'])} turns, ~{estimate / 60:.1f} min, {kinds}")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
